def mask_tags(text: str) -> tuple[str, list[str]]:
    """
    Converts tags like:
      [item]item_id_with_no_spaces[/item]  -> __1_ITEM_ID_WITH_NO_SPACES__
      [reputation=high]     -> __2_REPUTATION_HIGH__
      [/reputation]         -> __3_REPUTATION_CLOSE__
    and records original content in mapping.
    """
    mapping: list[str] = []

    def make_identifier(tag: str, inner: str | None = None, attr: str | None = None, closing: bool = False) -> str:
        if closing:
            base = f"{tag}_CLOSE"
        elif inner:
            base = f"{tag}_{inner}"
        elif attr:
            base = f"{tag}_{attr.lstrip('=')}"
        else:
            base = tag
        # sanitize: keep letters/numbers/underscore, collapse multiple underscores, uppercase
        ident = re.sub(r'[^0-9A-Za-z]+', '_', base)
        ident = re.sub(r'_+', '_', ident).strip('_').upper() or 'TAG'
        return ident

    # match [tag]inner[/tag], [tag=...]inner[/tag] with [a-zA-Z-_] in inner
    pattern_tags = re.compile(r'\[(\w+)(=[^\]]+)?\]([a-zA-Z-_]*?)\[/\1\]')
    def repl_tags(m: re.Match) -> str:
        tag = m.group(1)
        attr = m.group(2)
        inner = m.group(3)
        identifier = make_identifier(tag, inner=inner if inner else None, attr=attr, closing=False)
        mapping.append(m.group(0))
        return f"__{len(mapping)}_{identifier}__"
    text = pattern_tags.sub(repl_tags, text)

    # match [tag=...] and [/tag] separately
    pattern_reputation = re.compile(r'\[(\/?)(\w+)(=[^\]]+)?\]')
    def repl_reputation(m: re.Match) -> str:
        tag = m.group(2)
        attr = m.group(3)
        whole = m.group(0)
        
        closing = whole.startswith('[/')
        identifier = make_identifier(tag, inner=None, attr=attr, closing=closing)
        mapping.append(m.group(0))
        return f"__{len(mapping)}_{identifier}__"
    text = pattern_reputation.sub(repl_reputation, text)

    return (text, mapping)

def unmask_tags(text: str, mapping: list[str]) -> str:
    """
    Replaces placeholders like __1_ITEM_ID__ back to their original tag content using mapping.
    """
    def replacement(m: re.Match) -> str:
        index = int(m.group(1)) - 1
        if 0 <= index < len(mapping):
            return mapping[index]
        return m.group(0)


    pattern = re.compile(r'__([0-9]+)_[A-Z0-9_-]+__')
    
    # Repeatedly find and replace. We can't use `.sub` once... for some reason??
    while True:
        new_text = pattern.sub(replacement, text, 1)
        if new_text == text:
            break
        text = new_text
    
    return text


def create_po_file(translations: dict[str, tuple[str, str]], language: str):
    po = polib.POFile()
    po.header = "Autogenerated by localization/translate.py"
    po.metadata = {
        'Language': language,
        'Content-Type': 'text/plain; charset=utf-8',
    }

    for original, translated in translations.items():
        entry = polib.POEntry(
            msgid=original,
            msgstr=translated[0],
            msgctxt=translated[1]
        )
        po.append(entry)

    po.save(f'{language}.po')

def process_pot_file(pot_file_path, target_language):
    translations = {}
    
    pot_data = polib.pofile(pot_file_path)
    
    for entry in pot_data:
        line = entry.msgid
        
        if not line.strip():
            continue
        
        tl_desc = entry.comment if entry.comment else "general text"
        tl_desc = tl_desc.replace("TRANSLATORS: ", "")
        tl_desc = re.sub(r'\s+', ' ', tl_desc)
        tl_desc = tl_desc.strip()
        if entry.msgctxt:
            tl_desc += f" (Context: {entry.msgctxt})"
        
        (masked_line, mapping) = mask_tags(line)
        
        translated = translate_text(masked_line, tl_desc, target_language)
        
        final_translation = unmask_tags(translated, mapping)
        
        # print(f"Translated line: \"{line.strip()[:30]}\" to \"{final_translation.strip()[:30]}\"")
        
        translations[line] = (final_translation, entry.msgctxt)
    
    create_po_file(translations, target_language)

